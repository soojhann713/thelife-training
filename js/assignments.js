// 한 과정의 모든 과제를 평탄화 (group 라벨 포함)
export function courseAssignments(course) {
  if (!course) return [];
  return course.groups.flatMap((g) => g.items.map((it) => ({ ...it, group: g.label })));
}

// 코스를 RTDB 시드 형태로 변환: { label, tasks: { <id>: {title,kind,group,order,due,m,x} } }
export function courseSeed(course) {
  const tasks = {};
  courseAssignments(course).forEach((it, i) => {
    tasks[it.id] = {
      title: it.title, kind: it.kind, group: it.group || "",
      order: i, due: it.due || "", m: it.m || [], x: it.x || [],
    };
  });
  return { label: course.label, tasks };
}

